// Package generated holds request/response types produced mechanically
// from the GraphANN OpenAPI spec. Nothing in this package is hand-edited.
//
// Source spec:   api/openapi/spec.yaml (graphann server repo)
// Generator:     github.com/oapi-codegen/oapi-codegen/v2 (cmd/oapi-codegen)
// Command:
//
//	oapi-codegen -generate types -package generated \
//	    -o generated/types.go /path/to/graphann/api/openapi/spec.yaml
//
// See scripts/generate-types.sh for the exact invocation used to produce
// types.go, and generated_staleness_test.go (package graphann) for the
// check that fails CI if types.go drifts from what the spec would
// currently generate.
//
// DO NOT hand-edit types.go. Regenerate it instead — any manual change
// is silently discarded (and CI-detected as drift) on the next run of
// scripts/generate-types.sh.
package generated
